func TestAmneziaWGAllowedIPsWithoutTunnelIsFullTunnel(t *testing.T) {
	if got := AmneziaWGAllowedIPs(nil, []string{"77.88.8.8"}); got != FullTunnelAllowedIPs {
		t.Fatalf("AllowedIPs = %q, want %q", got, FullTunnelAllowedIPs)
	}
}
